#!/usr/bin/env bash
# The founder's local server (the 2026-11-12 directive item 1): one command
# takes the REAL stack up on this PC, seeds the founder's own driver and a
# Christchurch day, and proves the whole thing with the repo's own smoke test.
#
#   bash infra/local-stack.sh up      # tunnels -> build -> stack -> seed -> smoke
#   bash infra/local-stack.sh status  # what is running and at which URLs
#   bash infra/local-stack.sh smoke   # the smoke test again, on the live URLs
#   bash infra/local-stack.sh down    # stop the stack (the volumes stay)
#
# What it does NOT do: hold the machine. The directive's §0 caps the stack at
# 5 GB and 3 CPUs (this PC has 39.6 GB and 14 cores, so the >16 GB rule) - see
# infra/compose.local.yml, where every service carries its own limit and the
# file's header adds them up. The heavy-job lock (C:\Users\DCL\projects\
# .heavy-job.lock) is taken for the BUILD and the START only and released as
# soon as the stack is up: the running stack must not hold it, so the lead can
# build the app and run BlueStacks while the founder tests.
#
# The founder's password is written to .local-founder-login.txt and nowhere
# else - never to stdout, never to the log, never to git.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

ENV_FILE="$ROOT/infra/local/local.env"
HOST_FILE="$ROOT/infra/local/hostnames.env"
LOGIN_FILE="$ROOT/.local-founder-login.txt"
LOCK_FILE="${COURIER_HEAVY_LOCK:-C:/Users/DCL/projects/.heavy-job.lock}"
COMPOSE=(docker compose --env-file "$ENV_FILE" -f infra/compose.local.yml)

log() { printf '\n== %s ==\n' "$*"; }
fail() { printf 'local-stack: %s\n' "$*" >&2; exit 1; }

# ------------------------------------------------------------------ the lock
take_lock() {
  mkdir -p "$(dirname "$LOCK_FILE")"
  if [ -f "$LOCK_FILE" ]; then
    local age
    age="$(( $(date +%s) - $(stat -c %Y "$LOCK_FILE" 2>/dev/null || stat -f %m "$LOCK_FILE") ))"
    if [ "$age" -lt 3600 ]; then
      printf 'local-stack: the heavy-job lock is held by: %s\n' "$(cat "$LOCK_FILE")"
      fail "another session is building or starting something; try again later"
    fi
    printf 'local-stack: the lock was %s seconds old, treating it as stale\n' "$age"
    rm -f "$LOCK_FILE"
  fi
  printf 'backend-session %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$LOCK_FILE"
}

release_lock() { rm -f "$LOCK_FILE"; }
trap release_lock EXIT

# ------------------------------------------------------------------ the env
write_env() {
  # shellcheck disable=SC1090
  . "$HOST_FILE"
  local edge_host voice_host
  edge_host="${COURIER_EDGE_URL#https://}"
  voice_host="${COURIER_VOICE_URL#https://}"
  mkdir -p "$(dirname "$ENV_FILE")"

  # A generated strong password, written once and then reused: the founder's
  # account must not be re-created (and its day re-seeded) on every `up`.
  if [ ! -f "$ENV_FILE" ]; then
    local pg auth valkey pod founder
    pg="$(openssl rand -hex 24)"
    auth="$(openssl rand -hex 32)"
    valkey="$(openssl rand -hex 24)"
    # ADR-011: the API refuses to boot without the POD store's signing grant.
    pod="local-only-pod-signing-$(openssl rand -hex 16)"
    # The founder's own password: strong, generated here, and stored only in the
    # env file and .local-founder-login.txt.
    founder="$(openssl rand -base64 24 | tr -d '\n')"
    cat >"$ENV_FILE" <<ENV
# The founder's local stack environment. Generated by infra/local-stack.sh and
# git-ignored (infra/*.env). The tunnel hostnames are the only public values in
# here; everything else is this machine's own.
POSTGRES_USER=courier
POSTGRES_DB=courier
POSTGRES_PASSWORD=$pg
VALKEY_PASSWORD=$valkey
BETTER_AUTH_SECRET=$auth
POD_URL_SIGNING_SECRET=$pod
APP_VERSION=local-$(git rev-parse --short HEAD 2>/dev/null || echo dev)
COURIER_DOMAIN=$edge_host
ACME_EMAIL=founder@courier.local
AUTH_TRUSTED_ORIGINS=$COURIER_EDGE_URL,exp://,courier://
AUTH_JWT_ISSUER=$COURIER_EDGE_URL
API_ALLOWED_HOSTS=$edge_host,api,api_a,localhost,127.0.0.1,[::1]
FOUNDER_EMAIL=founder@courier.local
FOUNDER_PASSWORD=$founder
ENV
    log "the environment is generated (infra/local/local.env)"
  else
    # The tunnels' URLs change on every restart, so the four lines that carry
    # them are rewritten in place: a compose `up` then recreates the services
    # whose configuration changed, and the generated secrets are untouched.
    local tmp="$ENV_FILE.new"
    sed -e "s|^COURIER_DOMAIN=.*|COURIER_DOMAIN=$edge_host|" \
        -e "s|^AUTH_TRUSTED_ORIGINS=.*|AUTH_TRUSTED_ORIGINS=$COURIER_EDGE_URL,exp://,courier://|" \
        -e "s|^AUTH_JWT_ISSUER=.*|AUTH_JWT_ISSUER=$COURIER_EDGE_URL|" \
        -e "s|^API_ALLOWED_HOSTS=.*|API_ALLOWED_HOSTS=$edge_host,api,api_a,localhost,127.0.0.1,[::1]|" \
        "$ENV_FILE" > "$tmp"
    mv "$tmp" "$ENV_FILE"
    log "the environment follows the tunnels' new hostnames (infra/local/local.env)"
  fi
}

# ------------------------------------------------------------------ up
up() {
  take_lock
  bash infra/cloudflared.sh start
  # shellcheck disable=SC1090
  . "$HOST_FILE"
  write_env

  log "building the images (this is the only slow part)"
  "${COMPOSE[@]}" build --quiet

  # The order is the staging deploy's own (infra/deploy.sh): the database first,
  # then the auth service's OWN migration, and only then the services that read
  # it. Better Auth checks its schema when the service boots, so a container
  # started before its tables exist holds that verdict for its whole life - an
  # earlier version of this script started everything and migrated afterwards,
  # and sign-up answered 500 with a log that said nothing at all.
  log "the database, first"
  "${COMPOSE[@]}" up -d --wait postgres valkey

  migrate

  log "starting the stack"
  # --remove-orphans: a service rename (or a removed service) leaves the old
  # container holding its address, and the next `up` fails with "Address
  # already in use" - which reads like a network problem and is really a
  # leftover. Compose names them itself ("Found orphan containers"), and the flag
  # is the fix, not a cleanup for later.
  "${COMPOSE[@]}" up -d --wait --remove-orphans

  release_lock
  log "the stack is up (the lock is released: the running stack does not hold it)"

  seed
  smoke
  announce
}

# ------------------------------------------------------------------ migrate
migrate() {
  # The auth service's own tables: Better Auth creates them with its own
  # migration, and the contract's schema.sql does not carry them (the API's
  # tables and the auth service's tables are two migrations in one database -
  # services/auth/src/migrate.config.ts). The command is the one
  # infra/deploy.sh runs on the staging host, run INSIDE the auth image so the
  # service's own source, its dependencies and its compose environment are all
  # there (the deploy script's comment records the two host-side attempts that
  # failed with MODULE_NOT_FOUND and MissingEnvError).
  log "the auth service's own tables (Better Auth's migration)"
  "${COMPOSE[@]}" run --rm --no-deps -T auth_a \
    npx --yes auth migrate --yes --config src/migrate.config.ts \
    || fail "the auth migration failed: the stack cannot sign anyone in without it"
  log "the auth service's tables are in place"
}

# ------------------------------------------------------------------ seed
seed() {
  # shellcheck disable=SC1090
  . "$HOST_FILE"
  set -a; . "$ENV_FILE"; set +a
  local base="$COURIER_EDGE_URL"

  log "seeding the founder's driver and today's Christchurch day"
  # The account: one sign-up, idempotent (a second call is answered 422 and the
  # run below carries on, because the account already exists).
  curl -fsS --max-time 30 -X POST "$base/api/auth/sign-up/email" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"$FOUNDER_EMAIL\",\"password\":\"$FOUNDER_PASSWORD\",\"name\":\"The Founder\"}" \
    >/dev/null 2>&1 || log "the founder's account already exists (the sign-in below carries on)"

  # The token, with a retry: the auth service is recreated by the `up` above and
  # its first seconds can answer a sign-in that succeeds a moment later (the run
  # that taught us this answered 401 with a log that said nothing at all). A
  # seeding step that failed on the first answer would leave the founder with a
  # stack that works and no day on it. The curl's own failure is absorbed here on
  # purpose: `set -e` would otherwise end the script on the first non-2xx and the
  # retry below would never run.
  local token="" answer=""
  local attempt
  # The cached token first: a sign-in costs a request of the service's own
  # budget (Better Auth limits /sign-in/email to 10 requests per 15 minutes per
  # IP - the custom rule in services/auth/src/config.ts), and an automation that
  # signs in on every `up` spends the founder's own budget. A JWT that still
  # answers an authenticated call is reused. Behind the edge the client IP cannot
  # be resolved, so every request shares one bucket per path - which makes the
  # budget scarcer still.
  if [ -f "$ROOT/infra/local/founder-token.txt" ]; then
    token="$(cat "$ROOT/infra/local/founder-token.txt")"
    if ! curl -fsS --max-time 20 "$base/runs" -H "Authorization: Bearer $token" >/dev/null 2>&1; then
      token=""
    fi
  fi
  if [ -z "$token" ]; then
    for attempt in 1 2 3 4 5 6; do
      # ONE request, and it carries both the body (stdout) and the headers (a
      # file, `-D`): a second request to read `Retry-After` would spend the very
      # budget the header is telling us to wait out.
      answer="$(curl -sS --max-time 30 -X POST "$base/api/auth/sign-in/email" \
        -H 'Content-Type: application/json' \
        -d "{\"email\":\"$FOUNDER_EMAIL\",\"password\":\"$FOUNDER_PASSWORD\"}" \
        -D "$ROOT/infra/local/sign-in.headers" -w '\n%{http_code}' || true)"
      local http_code="${answer##*$'\n'}"
      answer="${answer%$'\n'*}"
      token="$(printf '%s' "$answer" | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')"
      [ -n "$token" ] && break
      # A 429 is the service's own sign-in budget (10 per 15 minutes per IP - the
      # custom rule in services/auth/src/config.ts), and it says how long is left
      # in `Retry-After`. Waiting that out ONCE is the whole difference between a
      # seed that works and one that spends the founder's own budget hammering a
      # closed window.
      local retry_after=""
      if [ "$http_code" = "429" ]; then
        retry_after="$(sed -n 's/.*[Rr]etry-[Aa]fter: *\([0-9]*\).*/\1/p' \
          "$ROOT/infra/local/sign-in.headers" | tr -d '\r')"
        [ -n "$retry_after" ] || retry_after=900
        log "the sign-in budget is spent for ${retry_after}s (the service's own rule); waiting it out"
        sleep "$retry_after"
        continue
      fi
      log "the sign-in did not answer a token (attempt $attempt): ${answer:0:160}"
      sleep 20
    done
  fi
  [ -n "$token" ] || fail "the sign-in did not return a token"

  # ADR-019: the demo day - five real Canterbury addresses near the Hornby
  # depot, a planned break, a priority stop, a delivery window and a pickup.
  #
  # The token the API takes is a JWT, and the sign-in's own token is NOT one:
  # Better Auth's session token is opaque, and `POST /demo/runs` with it answers
  # 401 (which is exactly what the first version of this step did). The jwt()
  # plugin mints a JWT from the SESSION COOKIE at GET /api/auth/token - so this
  # is two calls, and the second one's cookie comes from the sign-in's own
  # Set-Cookie header, which the `-D` file above captured.
  local cookie jwt
  cookie="$(sed -n 's/^[Ss]et-[Cc]ookie: *\([^;]*\).*/\1/p' \
    "$ROOT/infra/local/sign-in.headers" | tr -d '\r' | tail -1)"
  [ -n "$cookie" ] || fail "the sign-in carried no session cookie"
  jwt="$(curl -fsS --max-time 30 "$base/api/auth/token" -H "Cookie: $cookie" \
    | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')"
  [ -n "$jwt" ] || fail "the auth service did not mint a JWT from the session"

  curl -fsS --max-time 60 -X POST "$base/demo/runs" \
    -H 'Content-Type: application/json' \
    -H "Authorization: Bearer $jwt" \
    -d '{"reason":"demo"}' > "$ROOT/infra/local/demo-run.json"
  log "the demo day is seeded (infra/local/demo-run.json)"

  printf '%s\n' "$jwt" > "$ROOT/infra/local/founder-token.txt"
  chmod 600 "$ROOT/infra/local/founder-token.txt"

  # The password goes to the ONE file the directive names, and nowhere else.
  cat >"$LOGIN_FILE" <<LOGIN
The founder's local server (the 2026-11-12 directive item 1).

  API URL:     $COURIER_EDGE_URL            (EXPO_PUBLIC_API_URL)
  AUTH URL:    $COURIER_EDGE_URL/api/auth   (EXPO_PUBLIC_AUTH_URL)
  VOICE URL:   $COURIER_VOICE_URL           (EXPO_PUBLIC_VOICE_SERVICE_URL)

  Sign in with:
    email:     $FOUNDER_EMAIL
    password:  $FOUNDER_PASSWORD

The day is already seeded: one Christchurch run, five stops, a priority stop, a
delivery window and a pickup. Re-seed with:
  curl -fsS -X POST "\$API/demo/runs" -H "Authorization: Bearer <token>" \\
    -H 'Content-Type: application/json' -d '{"reason":"demo"}'

This file is git-ignored. The stack: bash infra/local-stack.sh down (to stop it).
LOGIN
  chmod 600 "$LOGIN_FILE"
  log "the founder's login is written to .local-founder-login.txt (git-ignored)"
}

# ------------------------------------------------------------------ smoke
smoke() {
  # shellcheck disable=SC1090
  . "$HOST_FILE"
  set -a; . "$ENV_FILE"; set +a
  local base="$COURIER_EDGE_URL"
  local host="${base#https://}"
  local token=""
  [ -f "$ROOT/infra/local/founder-token.txt" ] && token="$(cat "$ROOT/infra/local/founder-token.txt")"

  log "the repo's own smoke test against the live edge"
  # --no-version: this stack's APP_VERSION is a local sha, not a release, and
  # the flag exists exactly for that (infra/smoke.sh). The token proves the
  # authenticated round trip end to end.
  bash infra/smoke.sh --domain "$host" --port 443 --no-version --token "$token" \
    --evidence "$ROOT/infra/local/smoke-evidence" || fail "the smoke test failed (see above)"
}

# ------------------------------------------------------------------ announce
announce() {
  # shellcheck disable=SC1090
  . "$HOST_FILE"
  log "READY - the founder's URLs"
  printf '  API:    %s\n' "$COURIER_EDGE_URL"
  printf '  AUTH:   %s/api/auth\n' "$COURIER_EDGE_URL"
  printf '  VOICE:  %s\n' "$COURIER_VOICE_URL"
  printf '  LOGIN:  %s\n' "$LOGIN_FILE"
}

# ------------------------------------------------------------------ status
status() {
  "${COMPOSE[@]}" ps
  [ -f "$HOST_FILE" ] && cat "$HOST_FILE"
}

# ------------------------------------------------------------------ down
down() {
  log "stopping the stack (the volumes stay)"
  "${COMPOSE[@]}" down || true
  bash infra/cloudflared.sh stop || true
}

case "${1:-}" in
  up) up ;;
  status) status ;;
  smoke)
    seed
    smoke
    ;;
  down) down ;;
  *) fail "usage: infra/local-stack.sh up|status|smoke|down" ;;
esac
