#!/usr/bin/env python3
"""Split the Canterbury LINZ streets into a tune set and a HELD-OUT set.

Founder directive 2026-11-08 item 2: the accuracy target (>= 99.5 %, no slice
below 98 %) is measured on a held-out 20 % of the Canterbury STREETS - split by
STREET, never by address, so no street name appears on both sides and no
name-specific tuning can leak into the measurement. The split is seeded and the
held-out street list is COMMITTED (`services/api/tests/fixtures/linz-holdout-streets.txt`),
so every run measures the same streets. Tuning (error analysis, threshold work,
vocabulary) may only use the other 80 % of streets.

The street key mirrors `road_key()` in `services/api/app/address_correction.py`
(lower-case, punctuation folded, street type folded to its abbreviation), so
"Bealey Avenue" and "Bealey Ave" are one street, the way the engine sees them.

Reads only the build-local, gitignored index (`data/linz/addresses-<area>.jsonl`,
ADR-003); writes no address rows - just the derived street list.

Like every script in this folder: prints the plan and stops unless --execute.
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
from datetime import UTC, datetime
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCES = REPO / "data" / "linz"
AREAS = ("christchurch", "selwyn", "waimakariri")
OUT = REPO / "services" / "api" / "tests" / "fixtures" / "linz-holdout-streets.txt"

SEED = 20261108
HELDOUT_FRACTION = 0.20

# Mirrors _STREET_TYPES in services/api/app/address_correction.py (road_key).
_STREET_TYPES = {
    "street": "st", "st": "st", "road": "rd", "rd": "rd", "avenue": "ave",
    "ave": "ave", "drive": "dr", "dr": "dr", "place": "pl", "pl": "pl",
    "crescent": "cres", "cres": "cres", "terrace": "tce", "tce": "tce",
    "lane": "ln", "ln": "ln", "close": "cl", "cl": "cl", "court": "ct",
    "ct": "ct", "way": "way", "grove": "gr", "gr": "gr", "mews": "mews",
    "quay": "quay", "parade": "pde", "pde": "pde", "highway": "hwy",
    "hwy": "hwy", "square": "sq", "sq": "sq", "esplanade": "esp", "esp": "esp",
    "bypass": "byp", "byp": "byp", "motorway": "shwy", "shwy": "shwy",
}


def street_key(road: str) -> str:
    """The street identity: road_key()'s normalisation, kept in step by the
    accuracy suite (it imports the same table through the engine)."""
    text = re.sub(r"[^a-z0-9 ]+", " ", road.lower())
    tokens = [token for token in text.split() if token]
    if tokens and tokens[-1] in _STREET_TYPES:
        tokens[-1] = _STREET_TYPES[tokens[-1]]
    return " ".join(tokens)


def collect_streets() -> tuple[dict[str, int], dict[str, dict[str, int]]]:
    """street key -> address count, plus per-area street counts."""
    counts: dict[str, int] = {}
    per_area: dict[str, dict[str, int]] = {}
    for area in AREAS:
        path = SOURCES / f"addresses-{area}.jsonl"
        if not path.exists():
            print(f"missing {path} (run scripts/data/fetch-linz.py + build-linz-index.py first)")
            sys.exit(2)
        area_counts: dict[str, int] = {}
        with path.open(encoding="utf-8") as handle:
            for line in handle:
                row = json.loads(line)
                road = (row.get("road") or "").strip()
                if not road:
                    continue
                key = street_key(road)
                counts[key] = counts.get(key, 0) + 1
                area_counts[key] = area_counts.get(key, 0) + 1
        per_area[area] = area_counts
    return counts, per_area


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--execute", action="store_true", help="actually write the list")
    args = parser.parse_args()

    counts, per_area = collect_streets()
    streets = sorted(counts)
    randomizer = random.Random(SEED)
    shuffled = streets[:]
    randomizer.shuffle(shuffled)
    n_holdout = round(len(streets) * HELDOUT_FRACTION)
    heldout = sorted(shuffled[:n_holdout])
    heldout_set = set(heldout)

    heldout_addresses = sum(counts[s] for s in heldout)
    total_addresses = sum(counts.values())
    per_area_heldout = {
        area: sum(n for s, n in area_counts.items() if s in heldout_set)
        for area, area_counts in per_area.items()
    }

    lines = [
        "# HELD-OUT Canterbury streets for the D8 accuracy measurement",
        "# (founder directive 2026-11-08 item 2: split by STREET, never by address).",
        "# generated by: uv run python scripts/data/split-linz-holdout.py --execute",
        f"# generated at: {datetime.now(UTC).isoformat(timespec='seconds')}",
        f"# seed: {SEED}  held-out fraction: {HELDOUT_FRACTION:.0%}",
        f"# streets total: {len(streets)}  held out: {n_holdout}  tune: {len(streets) - n_holdout}",
        (
            f"# addresses total: {total_addresses:,}  on held-out streets: {heldout_addresses:,} "
            f"({heldout_addresses / total_addresses:.1%})"
        ),
        "# per area, addresses on held-out streets: "
        + ", ".join(f"{area}={n:,}" for area, n in per_area_heldout.items()),
        "# one street key per line (road_key() normalisation); never tune on these.",
        *heldout,
        "",
    ]

    print(f"plan: write {OUT.relative_to(REPO)}")
    print(f"  streets: {len(streets)} total, {n_holdout} held out ({HELDOUT_FRACTION:.0%}), seed {SEED}")
    print(f"  addresses: {total_addresses:,} total, {heldout_addresses:,} on held-out streets")
    print(f"  per area held-out addresses: {per_area_heldout}")
    if not args.execute:
        print("dry run: pass --execute to write")
        return

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size} bytes, {n_holdout} streets)")


if __name__ == "__main__":
    main()
